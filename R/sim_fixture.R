#' Read a Tier B replay fixture
#'
#' Fixtures are frozen recordings of the Python laser-cholera oracle: every
#' PRNG call it made, in order, plus the 28 result channels it produced. They
#' are generated once by \code{claude/oracle/dump_fixture.py} and committed, so
#' the replay tests run in pure R with no Python installed. See
#' \code{tests/testthat/fixtures/ORACLE.md} for the oracle provenance.
#'
#' @name sim_fixture
#' @keywords internal
NULL

# Oracle draw sites are recorded as `file:line` in the Python source, which is
# precise and stable but meaningless on the R side. This maps each to the
# engine's own site label so a replay mismatch reads in R's vocabulary.
#
# Maintained against laser-cholera v0.16.1 (commit 06938c1). If the oracle is
# ever regenerated from a different version these line numbers move, which is
# exactly why the fixture records its source SHA-256: a stale map produces an
# unmapped-site error rather than a silent mispairing.
.SIM_ORACLE_SITE_MAP <- c(
     "susceptible.py:135"  = "susceptible/non_disease_deaths",
     "susceptible.py:143"  = "susceptible/births",
     "exposed.py:94"       = "exposed/non_disease_deaths",
     "recovered.py:103"    = "recovered/non_disease_deaths",
     "recovered.py:110"    = "recovered/waning",
     "infectious.py:181"   = "infectious/sym_non_disease_deaths",
     "infectious.py:203"   = "infectious/disease_deaths",
     "infectious.py:210"   = "infectious/reported_deaths",
     "infectious.py:217"   = "infectious/sym_recovery",
     "infectious.py:231"   = "infectious/asym_non_disease_deaths",
     "infectious.py:239"   = "infectious/asym_recovery",
     "infectious.py:249"   = "infectious/progression",
     "infectious.py:267"   = "infectious/reported_cases",
     "vaccinated.py:157"   = "vaccinated/v1_non_disease_deaths",
     "vaccinated.py:163"   = "vaccinated/v2_non_disease_deaths",
     "vaccinated.py:170"   = "vaccinated/v1_waning",
     "vaccinated.py:175"   = "vaccinated/v2_waning",
     "humantohuman.py:165" = "humantohuman/infection",
     "envtohuman.py:133"   = "envtohuman/infection",
     "environmental.py:135"= "environmental/decay",
     "environmental.py:139"= "environmental/shedding_sym",
     "environmental.py:143"= "environmental/shedding_asym"
